#requires -Version 7
<#
.SYNOPSIS
  Generate every local credential into a git-ignored env file that docker compose reads on its own,
  and create the matching Kubernetes Secrets in the current kube context.
.DESCRIPTION
  Re-running the script never invalidates running databases or issued tokens: an existing env file keeps
  every value it has and only gains the keys added to this script since it was written.
  Delete the file (and the compose volumes) to start over.
  Unless -EnvFile is given, the three APIs' user-secrets are set from the same values, pointed at localhost,
  so `dotnet run` on the host reaches the compose datastores. The Secrets are applied idempotently into the
  kongroo namespace (created if missing), so a re-run on a live cluster changes nothing.
.PARAMETER EnvFile
  Env file to write. Default: .env at the Orchestration root. Passing it leaves user-secrets alone.
.PARAMETER Target
  Eks (eks/up.ps1): fresh values on every run into eks/.env, the Elastic Cloud user from the hand-filled eks/cloud.env in
  catalog-secret, Secrets applied to context kongroo-eks, no user-secrets. The local .env is never read or written.
.PARAMETER SkipUserSecrets
  Leave the APIs' user-secrets alone (check.ps1).
.PARAMETER SkipKubernetes
  Leave the cluster alone (compose-only hosts, check.ps1).
#>
param(
    [string]$EnvFile = (Join-Path (Split-Path $PSScriptRoot -Parent) ".env"),
    [ValidateSet("Local", "Eks")]
    [string]$Target = "Local",
    [switch]$SkipUserSecrets,
    [switch]$SkipKubernetes
)

$ErrorActionPreference = "Stop"

function New-RandomPassword([int]$Length = 32) {
    # Alphanumeric only: safe unescaped in connection strings, Mongo URIs and compose interpolation.
    $alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
    -join (1..$Length | ForEach-Object { $alphabet[[System.Security.Cryptography.RandomNumberGenerator]::GetInt32($alphabet.Length)] })
}

function New-HexKey([int]$Bytes = 32) {
    [Convert]::ToHexString([System.Security.Cryptography.RandomNumberGenerator]::GetBytes($Bytes)).ToLowerInvariant()
}

function ConvertTo-HostValue([string]$Value) {
    # .env names the datastores by compose service; a host run reaches them on compose's published ports.
    $Value -replace 'Host=[^;]+;', 'Host=localhost;' -replace '@[^@:/]+:', '@localhost:' -replace '^[^:=;/@]+:(?=\d+$)', 'localhost:'
}

function New-LocalSecrets([hashtable]$Existing = @{}) {
    # Connection strings derive from the existing passwords, so keys appended to an older env file still match it.
    $postgresPassword = $Existing.POSTGRES_PASSWORD ?? (New-RandomPassword)
    $mongoPassword = $Existing.MONGO_PASSWORD ?? (New-RandomPassword)
    [ordered]@{
        POSTGRES_PASSWORD                   = $postgresPassword
        RABBITMQ_PASSWORD                   = New-RandomPassword
        MONGO_PASSWORD                      = $mongoPassword
        GRAFANA_ADMIN_PASSWORD              = New-RandomPassword
        ELASTIC_PASSWORD                    = New-RandomPassword
        JWT_SIGNING_KEY                     = New-HexKey
        # Identity requires a letter, a digit and a special character.
        BOOTSTRAP_ADMIN_PASSWORD            = "$(New-RandomPassword)-1"
        IDENTITY_DATABASE_CONNECTION_STRING = "Host=postgres;Database=kongroo_identity;Username=kongroo;Password=$postgresPassword"
        CATALOG_DATABASE_CONNECTION_STRING  = "Host=postgres;Database=kongroo_catalog;Username=kongroo;Password=$postgresPassword"
        PAYMENTS_DATABASE_CONNECTION_STRING = "Host=postgres;Database=kongroo_payments;Username=kongroo;Password=$postgresPassword"
        MONGO_CONNECTION_STRING             = "mongodb://kongroo:$mongoPassword@mongodb:27017/kongroo_catalog?authSource=admin"
        REDIS_CONNECTION_STRING             = "redis:6379"
    }
}

function Format-EnvLines($Entries) {
    $Entries | ForEach-Object { "$($_.Key)=$($_.Value)" }
}

function Write-EnvFile([string]$Path, [System.Collections.Specialized.OrderedDictionary]$Values) {
    $lines = @("# Generated by scripts/new-secrets.ps1. Local only, never commit.")
    $lines += Format-EnvLines $Values.GetEnumerator()
    Set-Content -Path $Path -Value (($lines -join "`n") + "`n") -NoNewline
}

function Read-EnvFile([string]$Path) {
    ConvertFrom-StringData "$(Get-Content -Raw $Path)"
}

$isEks = $Target -eq "Eks"
if ($isEks) {
    if ($PSBoundParameters.ContainsKey("EnvFile")) { throw "-Target Eks always writes eks/.env; drop -EnvFile." }
    $eksFolder = Join-Path (Split-Path $PSScriptRoot -Parent) "eks"
    . "$eksFolder/common.ps1"
    $EnvFile = Join-Path $eksFolder ".env"
    $cloud = Read-CloudEnv
}

# $secrets holds the effective values either way, so later targets (k8s Secrets, user-secrets) build from it.
# EKS gets fresh values every cloud day, so cloud and local never share a credential.
$secrets = if (-not $isEks -and (Test-Path $EnvFile)) {
    $existing = Read-EnvFile $EnvFile
    $missing = (New-LocalSecrets $existing).GetEnumerator() | Where-Object { -not $existing.ContainsKey($_.Key) }
    if ($missing) {
        $content = Get-Content -Raw $EnvFile
        $separator = $content -and -not $content.EndsWith("`n") ? "`n" : ""
        [IO.File]::AppendAllText($EnvFile, $separator + ((Format-EnvLines $missing) -join "`n") + "`n")
        Write-Host "$EnvFile existed; appended $(@($missing.Key) -join ', ')." -ForegroundColor Green
        Read-EnvFile $EnvFile
    }
    else {
        Write-Host "$EnvFile already exists; left untouched."
        $existing
    }
}
else {
    $generated = New-LocalSecrets
    Write-EnvFile $EnvFile $generated
    Write-Host "Wrote $EnvFile." -ForegroundColor Green
    $generated
}

$apiSecrets = [ordered]@{
    Identity = [ordered]@{
        ConnectionStrings__Database = $secrets.IDENTITY_DATABASE_CONNECTION_STRING
        Jwt__SigningKey             = $secrets.JWT_SIGNING_KEY
        BootstrapAdmin__Password    = $secrets.BOOTSTRAP_ADMIN_PASSWORD
        RabbitMq__User              = "kongroo"
        RabbitMq__Pass              = $secrets.RABBITMQ_PASSWORD
    }
    Catalog  = [ordered]@{
        ConnectionStrings__Database = $secrets.CATALOG_DATABASE_CONNECTION_STRING
        Jwt__SigningKey             = $secrets.JWT_SIGNING_KEY
        RabbitMq__User              = "kongroo"
        RabbitMq__Pass              = $secrets.RABBITMQ_PASSWORD
        Mongo__ConnectionString     = $secrets.MONGO_CONNECTION_STRING
        ConnectionStrings__Redis    = $secrets.REDIS_CONNECTION_STRING
        Search__Password            = $secrets.ELASTIC_PASSWORD
    }
    Payments = [ordered]@{
        ConnectionStrings__Database = $secrets.PAYMENTS_DATABASE_CONNECTION_STRING
        Jwt__SigningKey             = $secrets.JWT_SIGNING_KEY
        RabbitMq__User              = "kongroo"
        RabbitMq__Pass              = $secrets.RABBITMQ_PASSWORD
    }
}
if ($isEks) {
    # catalog-secret comes after catalog-config in envFrom, so these override the local Elasticsearch URI.
    $apiSecrets.Catalog.Search__Uri = $cloud.SEARCH_URI
    $apiSecrets.Catalog.Search__Username = $cloud.SEARCH_USERNAME
    $apiSecrets.Catalog.Search__Password = $cloud.SEARCH_PASSWORD
}

foreach ($api in $apiSecrets.GetEnumerator()) {
    $missing = @($api.Value.GetEnumerator() | Where-Object { -not $_.Value } | ForEach-Object Key)
    if ($missing) { throw "$EnvFile lacks a value for $($api.Key): $($missing -join ', ')" }
}

if (-not $SkipUserSecrets -and -not $isEks -and -not $PSBoundParameters.ContainsKey("EnvFile")) {
    $workspace = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
    foreach ($api in $apiSecrets.GetEnumerator()) {
        $project = Join-Path $workspace "Kongroo.$($api.Key)/src/Kongroo.$($api.Key)"
        $values = [ordered]@{}
        foreach ($entry in $api.Value.GetEnumerator()) { $values[$entry.Key -replace '__', ':'] = ConvertTo-HostValue $entry.Value }
        # Piped JSON keeps the values off the command line; output is shown only on failure.
        $output = $values | ConvertTo-Json -Compress | dotnet user-secrets set --project $project 2>&1
        if ($LASTEXITCODE -ne 0) { throw "dotnet user-secrets set failed for $project`: $output Pass -SkipUserSecrets to skip host runs." }
    }
    Write-Host "User-secrets set for Identity, Catalog and Payments (dotnet run against compose)." -ForegroundColor Green
}

if ($SkipKubernetes) { return }

$namespace = "kongroo"
$kubernetesSecrets = [ordered]@{
    "identity-secret"      = $apiSecrets.Identity
    "catalog-secret"       = $apiSecrets.Catalog
    "payments-secret"      = $apiSecrets.Payments
    "postgres-secret"      = [ordered]@{ POSTGRES_PASSWORD = $secrets.POSTGRES_PASSWORD }
    "rabbitmq-secret"      = [ordered]@{ RABBITMQ_DEFAULT_USER = "kongroo"; RABBITMQ_DEFAULT_PASS = $secrets.RABBITMQ_PASSWORD }
    "mongodb-secret"       = [ordered]@{ MONGO_INITDB_ROOT_USERNAME = "kongroo"; MONGO_INITDB_ROOT_PASSWORD = $secrets.MONGO_PASSWORD }
    "grafana-secret"       = [ordered]@{ GF_SECURITY_ADMIN_PASSWORD = $secrets.GRAFANA_ADMIN_PASSWORD }
    "kong-secret"          = [ordered]@{ JWT_SIGNING_KEY = $secrets.JWT_SIGNING_KEY }
    "elasticsearch-secret" = [ordered]@{ ELASTIC_PASSWORD = $secrets.ELASTIC_PASSWORD }
}
# The EKS overlay runs neither RabbitMQ (SNS/SQS instead) nor a local Elasticsearch (Elastic Cloud instead).
if ($isEks) { "rabbitmq-secret", "elasticsearch-secret" | ForEach-Object { $kubernetesSecrets.Remove($_) } }
# The EKS context is always named; the current context is never changed.
$kubeContext = $isEks ? $kubeContext : (kubectl config current-context)
$contextArguments = $isEks ? @("--context", $kubeContext) : @()

function Invoke-KubectlApply([string[]]$CreateArguments) {
    # create --dry-run | apply: creates or updates, and reports "unchanged" when nothing differs.
    kubectl @contextArguments create @CreateArguments --dry-run=client -o yaml | kubectl @contextArguments apply -f -
    if ($LASTEXITCODE -ne 0) { throw "kubectl apply failed for $($CreateArguments[0..2] -join ' ') (context: $kubeContext). Pass -SkipKubernetes for compose only." }
}

# Only when missing: re-applying would fight kubectl apply -k over the namespace's last-applied annotation.
if (-not (kubectl @contextArguments get namespace $namespace --ignore-not-found -o name)) { Invoke-KubectlApply @("namespace", $namespace) }
foreach ($secret in $kubernetesSecrets.GetEnumerator()) {
    $missing = @($secret.Value.GetEnumerator() | Where-Object { -not $_.Value } | ForEach-Object Key)
    if ($missing) { throw "$EnvFile lacks a value for $($secret.Key): $($missing -join ', ')" }
    $literals = $secret.Value.GetEnumerator() | ForEach-Object { "--from-literal=$($_.Key)=$($_.Value)" }
    Invoke-KubectlApply (@("secret", "generic", $secret.Key, "--namespace", $namespace) + $literals)
}
Write-Host "Kubernetes Secrets applied to namespace $namespace in context $kubeContext." -ForegroundColor Green
